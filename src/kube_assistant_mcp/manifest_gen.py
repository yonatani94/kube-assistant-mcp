"""Generates plain Kubernetes manifests and minimal Helm chart scaffolding.

Kept dependency-free (just PyYAML) so it can run in any environment,
including inside the MCP server response path where we want fast, synchronous
generation without shelling out to `helm create`.
"""

from __future__ import annotations

import textwrap
from dataclasses import dataclass
from pathlib import Path

import yaml


@dataclass
class DeploymentSpec:
    name: str
    namespace: str = "default"
    image: str = "nginx:latest"
    replicas: int = 1
    container_port: int = 8080
    cpu_request: str = "100m"
    cpu_limit: str = "500m"
    memory_request: str = "128Mi"
    memory_limit: str = "512Mi"
    env: dict[str, str] | None = None
    liveness_path: str | None = None
    readiness_path: str | None = None


class ManifestGenerator:
    """Builds Deployment/Service manifests and a minimal Helm chart tree."""

    def deployment_manifest(self, spec: DeploymentSpec) -> dict:
        container: dict = {
            "name": spec.name,
            "image": spec.image,
            "ports": [{"containerPort": spec.container_port}],
            "resources": {
                "requests": {"cpu": spec.cpu_request, "memory": spec.memory_request},
                "limits": {"cpu": spec.cpu_limit, "memory": spec.memory_limit},
            },
        }
        if spec.env:
            container["env"] = [{"name": k, "value": v} for k, v in spec.env.items()]
        if spec.liveness_path:
            container["livenessProbe"] = {
                "httpGet": {"path": spec.liveness_path, "port": spec.container_port},
                "initialDelaySeconds": 10,
                "periodSeconds": 15,
            }
        if spec.readiness_path:
            container["readinessProbe"] = {
                "httpGet": {"path": spec.readiness_path, "port": spec.container_port},
                "initialDelaySeconds": 5,
                "periodSeconds": 10,
            }

        return {
            "apiVersion": "apps/v1",
            "kind": "Deployment",
            "metadata": {"name": spec.name, "namespace": spec.namespace, "labels": {"app": spec.name}},
            "spec": {
                "replicas": spec.replicas,
                "selector": {"matchLabels": {"app": spec.name}},
                "template": {
                    "metadata": {"labels": {"app": spec.name}},
                    "spec": {"containers": [container]},
                },
            },
        }

    def service_manifest(self, spec: DeploymentSpec, service_port: int = 80) -> dict:
        return {
            "apiVersion": "v1",
            "kind": "Service",
            "metadata": {"name": f"{spec.name}-svc", "namespace": spec.namespace},
            "spec": {
                "selector": {"app": spec.name},
                "ports": [{"port": service_port, "targetPort": spec.container_port}],
                "type": "ClusterIP",
            },
        }

    def to_yaml(self, *manifests: dict) -> str:
        return "---\n".join(yaml.safe_dump(m, sort_keys=False) for m in manifests)

    # ------------------------------------------------------------------ #
    # Helm scaffolding
    # ------------------------------------------------------------------ #
    def write_helm_chart(self, spec: DeploymentSpec, output_dir: Path) -> Path:
        """Writes a minimal, valid Helm chart to output_dir/<name>/ and
        returns the chart directory path.
        """
        chart_dir = output_dir / spec.name
        templates_dir = chart_dir / "templates"
        templates_dir.mkdir(parents=True, exist_ok=True)

        (chart_dir / "Chart.yaml").write_text(
            yaml.safe_dump(
                {
                    "apiVersion": "v2",
                    "name": spec.name,
                    "description": f"Helm chart for {spec.name}, generated by kube-assistant-mcp",
                    "type": "application",
                    "version": "0.1.0",
                    "appVersion": "1.0.0",
                },
                sort_keys=False,
            )
        )

        values = {
            "replicaCount": spec.replicas,
            "image": {"repository": spec.image.split(":")[0], "tag": spec.image.split(":")[-1]},
            "containerPort": spec.container_port,
            "resources": {
                "requests": {"cpu": spec.cpu_request, "memory": spec.memory_request},
                "limits": {"cpu": spec.cpu_limit, "memory": spec.memory_limit},
            },
            "service": {"port": 80},
        }
        (chart_dir / "values.yaml").write_text(yaml.safe_dump(values, sort_keys=False))

        deployment_tpl = textwrap.dedent(
            f"""\
            apiVersion: apps/v1
            kind: Deployment
            metadata:
              name: {{{{ .Release.Name }}}}-{spec.name}
            spec:
              replicas: {{{{ .Values.replicaCount }}}}
              selector:
                matchLabels:
                  app: {spec.name}
              template:
                metadata:
                  labels:
                    app: {spec.name}
                spec:
                  containers:
                    - name: {spec.name}
                      image: "{{{{ .Values.image.repository }}}}:{{{{ .Values.image.tag }}}}"
                      ports:
                        - containerPort: {{{{ .Values.containerPort }}}}
                      resources:
                        {{{{- toYaml .Values.resources | nindent 8 }}}}
            """
        )
        (templates_dir / "deployment.yaml").write_text(deployment_tpl)

        service_tpl = textwrap.dedent(
            f"""\
            apiVersion: v1
            kind: Service
            metadata:
              name: {{{{ .Release.Name }}}}-{spec.name}-svc
            spec:
              selector:
                app: {spec.name}
              ports:
                - port: {{{{ .Values.service.port }}}}
                  targetPort: {{{{ .Values.containerPort }}}}
            """
        )
        (templates_dir / "service.yaml").write_text(service_tpl)

        (chart_dir / ".helmignore").write_text("*.swp\n.git/\n")

        return chart_dir
